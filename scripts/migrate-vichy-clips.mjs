import pg from 'pg';
export async function migrateVichyClips(client) {
  await client.query('BEGIN');
  try {
    await client.query("SET LOCAL lock_timeout = '5s'");
    await client.query("SET LOCAL statement_timeout = '30s'");
    await client.query('SELECT pg_advisory_xact_lock(782341904)');
    const identity=await client.query("SELECT format_type(atttypid,atttypmod) AS type FROM pg_attribute WHERE attrelid='users'::regclass AND attname='id'");
    if(identity.rows[0]?.type!=='text')throw new Error('Publication migration requires existing TEXT account IDs');
    await client.query(`CREATE TABLE IF NOT EXISTS vichy_clips (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000) PRIMARY KEY,
      code TEXT NOT NULL UNIQUE CHECK (code ~ '^HELX-[0-9]{6}$'),
      user_id TEXT NOT NULL REFERENCES users(id), username TEXT NOT NULL,
      title TEXT NOT NULL, original_name TEXT NOT NULL,
      object_key TEXT NOT NULL UNIQUE, content_type TEXT NOT NULL,
      size_bytes BIGINT NOT NULL CHECK(size_bytes>0),
      duration_sec DOUBLE PRECISION NOT NULL CHECK(duration_sec>=60),
      created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )`);
    await client.query(`CREATE TABLE IF NOT EXISTS vichy_clip_uploads (
      id UUID PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id),
      object_key TEXT NOT NULL UNIQUE, title TEXT NOT NULL, original_name TEXT NOT NULL,
      content_type TEXT NOT NULL, size_bytes BIGINT NOT NULL CHECK(size_bytes>0),
      state TEXT NOT NULL DEFAULT 'pending' CHECK(state IN ('pending','published','deleted')),
      clip_id INTEGER REFERENCES vichy_clips(id), created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      expires_at TIMESTAMPTZ NOT NULL
    )`);
    // Remove only the two audited application upper-size constraints.
    // Preserve positivity, integer storage, ownership, and the minimum duration.
    // This runs only in the explicitly requested migration, never on startup.
    for(const table of ['vichy_clips','vichy_clip_uploads']) {
      const name=table+'_size_bytes_check';
      const existing=await client.query('SELECT pg_get_constraintdef(oid) AS definition FROM pg_constraint WHERE conrelid=$1::regclass AND conname=$2 AND contype=\'c\'', [table,name]);
      const normalized=existing.rows[0]?.definition?.replace(/::bigint|CHECK|[()\s']/g,'');
      if(existing.rows.length!==1 || !['size_bytes>0','size_bytes>0ANDsize_bytes<=104857600','size_bytes>0ANDsize_bytes<=2147483648'].includes(normalized)) throw new Error('Unexpected publication size constraint; review schema before migration');
      if(normalized!=='size_bytes>0') {
        await client.query(`ALTER TABLE "${table}" DROP CONSTRAINT "${name}", ADD CONSTRAINT "${name}" CHECK(size_bytes>0)`);
      }
    }
    await client.query('CREATE INDEX IF NOT EXISTS vichy_clip_uploads_owner ON vichy_clip_uploads(user_id,created_at)');
    await client.query('COMMIT');
    console.log('Durable publication tables verified. Existing users and content untouched.');
  } catch(error){await client.query('ROLLBACK').catch(()=>{});throw error;}
}
export async function runVichyMigration(){
  if(!process.env.DATABASE_URL)throw new Error('DATABASE_URL required');
  const client=new pg.Client({connectionString:process.env.DATABASE_URL,connectionTimeoutMillis:5000});
  try{await client.connect();await migrateVichyClips(client);}finally{await client.end();}
}
