export function useSocialI18n() {
  const { lang } = useLang();
  const resolvedLang: SocialLocale =
    lang === "fr" || lang === "ar" || lang === "es" || lang === "de" ? lang : "en";
  return {
    lang: resolvedLang,
    locale: resolvedLang === "de" ? "de-DE" : resolvedLang,
    dir: resolvedLang === "ar" ? "rtl" : "ltr",
    st: SOCIAL_T[resolvedLang] as SocialDictionary,
  };
}

export function timeAgo(dateStr: string, st: Record<string, string>, locale = "en"): string {
  const diff = Math.floor((Date.now() - new Date(dateStr).getTime()) / 1000);
  if (!Number.isFinite(diff) || diff < 60) return st.just_now;
  const rtf = new Intl.RelativeTimeFormat(locale, { numeric: "always", style: "short" });
  if (diff < 3600) return rtf.format(-Math.floor(diff / 60), "minute");
  if (diff < 86400) return rtf.format(-Math.floor(diff / 3600), "hour");
  return rtf.format(-Math.floor(diff / 86400), "day");
}

