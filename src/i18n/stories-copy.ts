const copies: Record<Lang, StoryCopy> = { en, fr, ar, es, de };

/** Supported-locale dictionaries exposed for translation parity audits. */
export const STORIES_COPY = copies;

export function storiesCopy(lang: Lang, key: StoryCopyKey, values?: Record<string, string | number>) {
  let text: string = copies[lang][key];
  for (const [name, value] of Object.entries(values ?? {})) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function storiesLocale(lang: Lang) {
  if (lang === "ar") return "ar";
  if (lang === "fr") return "fr";
  if (lang === "es") return "es";
  if (lang === "de") return "de-DE";
  return "en";
}