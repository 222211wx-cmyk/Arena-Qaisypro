/** Read-only transposed locale table for translation parity audits. */
export const DASHBOARD_COPY_TABLE = Object.fromEntries(
  Object.entries(copy).map(([key, translations]) => [
    key,
    { ...translations, de: de[key as keyof typeof copy] },
  ]),
) as { [K in keyof typeof copy]: Record<Lang, string> };

export type DashboardCopyKey = keyof typeof copy;

export function dashboardText(lang: Lang, key: DashboardCopyKey, vars: Record<string, string | number> = {}) {
  return DASHBOARD_COPY_TABLE[key][lang].replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
}

export function dashboardLocale(lang: Lang) {
  return lang === "fr" ? "fr-FR" : lang === "ar" ? "ar-MA" : lang === "es" ? "es-ES" : lang === "de" ? "de-DE" : "en-US";
}