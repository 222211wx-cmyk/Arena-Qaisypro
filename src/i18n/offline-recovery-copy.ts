export type OfflineRecoveryErrorKind = "password" | "rate" | "network" | "invalid" | "generic" | "abort";

/** Classifies generated-client failures without inspecting secret request bodies. */
export function offlineRecoveryErrorKind(error: unknown): OfflineRecoveryErrorKind {
  if (error instanceof DOMException && error.name === "AbortError") return "abort";
  const status = typeof error === "object" && error && "status" in error ? Number((error as { status: unknown }).status) : NaN;
  if (status === 403) return "password";
  if (status === 429) return "rate";
  if (status === 400) return "invalid";
  if (Number.isNaN(status) || status === 0 || status >= 502) return "network";
  return "generic";
}
