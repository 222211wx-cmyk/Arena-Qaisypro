interface LangContextType {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
}

const LangContext = createContext<LangContextType>({
  lang: "ar",
  setLang: () => {},
  t: (k) => k,
});

// Arabic is the canonical first-visit language. A citizen's explicit choice persists.
function detectInitialLang(): Lang {
  const requested = new URLSearchParams(window.location.search).get("lang");
  if (requested && (["ar", "en", "fr", "es", "de"] as string[]).includes(requested)) {
    return requested as Lang;
  }
  const stored = localStorage.getItem("gdna_lang") as Lang | null;
  if (stored && (["ar", "en", "fr", "es", "de"] as string[]).includes(stored)) return stored;
  return "ar";
}

export function LangProvider({ children, manageDocument = true }: { children: ReactNode; manageDocument?: boolean }) {
  const [lang, setLangState] = useState<Lang>(detectInitialLang);
  useEffect(()=>{
    registerCloneDictionaries(T);
    const change=(event:Event)=>{const code=(event as CustomEvent<string>).detail;const mapped=code==='ar-MA'||code==='ary'||code==='tzm'?'ar':code;if(['ar','fr','en','es','de'].includes(mapped)){try{localStorage.setItem('gdna_lang',mapped);}catch{}setLangState(mapped as Lang);}};
    window.addEventListener('ameeq-language',change);
    return ()=>window.removeEventListener('ameeq-language',change);
  },[]);


  const setLang = (l: Lang) => {
    localStorage.setItem("gdna_lang", l);
    setLangState(l);
  };

  // Apply RTL/LTR to <html> whenever language changes
  useEffect(() => {
    // Supplementary React islands must not change a vanilla shell's language.
    if (!manageDocument) return;
    document.documentElement.dir  = lang === "ar" ? "rtl" : "ltr";
    document.documentElement.lang = lang;
  }, [lang, manageDocument]);

  const t = (key: string): string => {
    return T[lang]?.[key] ?? key;
  };

  return (
    <LangContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang() {
  return useContext(LangContext);
}

